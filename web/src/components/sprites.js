// --- colour helpers -------------------------------------------------------
function rgb(color) {
  if (color.startsWith('#')) {
    const n = parseInt(color.slice(1), 16);
    return [n >> 16 & 255, n >> 8 & 255, n & 255];
  }
  const m = color.match(/\d+(\.\d+)?/g)?.map(Number) || [128, 128, 128];
  if (color.startsWith('hsl')) {
    const [h, s, l] = [m[0], m[1] / 100, m[2] / 100];
    const k = n => (n + h / 30) % 12, a = s * Math.min(l, 1 - l);
    const f = n => l - a * Math.max(-1, Math.min(k(n) - 3, 9 - k(n), 1));
    return [f(0), f(8), f(4)].map(v => Math.round(v * 255));
  }
  return m.slice(0, 3);
}
const mix = (c, t, p) => c.map((v, i) => Math.round(v + (t[i] - v) * p));
const hex = c => `#${c.map(v => Math.max(0, Math.min(255, v)).toString(16).padStart(2, '0')).join('')}`;
const lum = c => (0.299 * c[0] + 0.587 * c[1] + 0.114 * c[2]) / 255;

function palette(color, accent) {
  const base = rgb(color);
  const dark = lum(base) < 0.22;
  return {
    a: hex(base),
    b: hex(mix(base, [255, 255, 255], dark ? 0.28 : 0.38)),
    c: hex(mix(base, [0, 0, 0], 0.3)),
    o: hex(mix(base, [0, 0, 0], dark ? 0.55 : 0.7)),
    w: '#ffffff',
    h: '#9b7448', H: '#6b4a2b',
    s: accent || hex(mix(base, [255, 255, 255], 0.65)),
  };
}

const cache = new Map();

/** data: URL of an SVG sprite for the given template and material colour. */
export function spriteUrl(shape, color, accent) {
  const key = `${shape}|${color}|${accent || ''}`;
  let url = cache.get(key);
  if (url) return url;
  const pal = palette(color, accent);
  const rows = T[shape] || T.orb;
  let rects = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < 16;) {
      const ch = row[x];
      if (ch === '.' || ch === undefined) { x++; continue; }
      let w = 1;
      while (row[x + w] === ch) w++;
      rects += `<rect x="${x}" y="${y}" width="${w}" height="1" fill="${pal[ch] || pal.a}"/>`;
      x += w;
    }
  });
  url = `data:image/svg+xml,${encodeURIComponent(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" shape-rendering="crispEdges">${rects}</svg>`)}`;
  cache.set(key, url);
  return url;
}

